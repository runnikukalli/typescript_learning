let x1: number = 10, y1: number = 20;

if (x1 == y1) {
    console.log("x1 and y1 are equal");
} else {
    console.log("x1 and y1 are not equal");
}

// === strict equality operator checks for both value and type equality
if (x1 === y1) {
    console.log("x1 and y1 are strictly equal");
} else {
    console.log("x1 and y1 are not strictly equal");
}

